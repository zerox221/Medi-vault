import mongoose from "mongoose";

const medicalRecordSchema = new mongoose.Schema(
  {
    patient: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },
    title: {
      type: String,
      required: [true, "Report title is required"],
      trim: true,
    },
    hospital: {
      type: String,
      default: "Diagnostic Center",
      trim: true,
    },
    category: {
      type: String,
      enum: [
        "Lab Reports",
        "Blood Test",
        "Blood Sugar",
        "Prescription",
        "Prescriptions",
        "Cardiology",
        "Radiology",
        "General Checkup",
        "Other",
      ],
      default: "Lab Reports",
    },
    doctorName: {
      type: String,
      default: "",
    },
    reportDate: {
      type: String,
      default: () => new Date().toISOString().split("T")[0],
    },
    fileUrl: {
      type: String,
      required: true,
    },
    publicId: {
      type: String,
      required: true,
    },
    fileSize: {
      type: String,
      default: "1.0 MB",
    },
    fileType: {
      type: String,
      default: "application/pdf",
    },
    extractedText: {
      type: String,
      default: "",
    },
    aiSummary: {
      summary: { type: String, default: "" },
      reportType: { type: String, default: "" },
      patientName: { type: String, default: "" },
      patientAge: { type: String, default: "" },
      labName: { type: String, default: "" },
      doctorName: { type: String, default: "" },
      findings: [{ type: String }],
      abnormalValues: [{ type: String }],
      keyBiomarkers: [
        {
          parameter: String,
          value: String,
          normalRange: String,
          flag: String,
        },
      ],
      disclaimer: {
        type: String,
        default:
          "This summary is generated by MediVault AI for informational guidance only. It is not a clinical medical diagnosis. Please consult a qualified doctor for interpretation and treatment decisions.",
      },
      generatedAt: { type: Date },
    },
    tags: [{ type: String }],
    processingStatus: {
      type: String,
      enum: ["uploaded", "processing", "completed", "failed"],
      default: "uploaded",
      index: true,
    },
    processingError: {
      type: String,
      default: "",
    },
    chunkCount: {
      type: Number,
      default: 0,
    },
    pageCount: {
      type: Number,
      default: 1,
    },
  },
  {
    timestamps: true,
  }
);

export const MedicalRecord = mongoose.model("MedicalRecord", medicalRecordSchema);
